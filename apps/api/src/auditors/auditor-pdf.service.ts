import { Injectable } from '@nestjs/common';
import PDFDocument from 'pdfkit';
import { registerPdfFonts, pdfLang, type PdfLang } from '../common/pdf-locale';

export interface QuotePdfData {
  quoteNo: string;
  invoiceNo: string | null;
  status: string;
  description: string;
  amount: number;
  gstApplicable: boolean;
  gstPercent: number;
  gstAmount: number;
  total: number;
  billingType: string;
  dueDate: Date | null;
  notes: string | null;
  createdAt: Date;
  auditor: {
    displayName: string;
    firmName: string | null;
    email: string | null;
    phone: string | null;
    city: string | null;
    state: string | null;
  };
  client: { name: string; email: string };
}

